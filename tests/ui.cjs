const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

async function run() {
  const chrome = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
  const browser = await chromium.launch(fs.existsSync(chrome) ? { executablePath: chrome } : {});
  const output = path.resolve(__dirname, '../test-results');
  fs.mkdirSync(output, { recursive: true });
  const url = pathToFileURL(path.resolve(__dirname, '../app/src/main/assets/index.html')).href;
  const errors = [];
  const requests = [];
  const checks = [];
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, timezoneId: 'Asia/Shanghai', reducedMotion: 'reduce' });
    context.setDefaultTimeout(10000);
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    page.on('request', request => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
    await page.clock.install({ time: new Date('2026-10-13T12:00:00+08:00') });
    await page.goto(url);
    assert.match(await page.locator('#almanac-gz-header').textContent(), /戊戌月 庚申日/);
    assert.equal(await page.locator('#app-error').isVisible(), false);
    for (const [selector, tab, title] of [['.zodiac-pill-item','zodiac','#zodiac-title'],['.czodiac-pill-item','almanac','#czodiac-title']]) {
      await page.locator('#tab-sub-' + tab).click();
      for (const pill of await page.locator(selector).all()) {
        const name = await pill.textContent();
        await pill.click();
        assert.equal(await page.locator(title).textContent(), name);
      }
    }
    checks.push('24星座/生肖切换');
    await page.reload();
    assert.match(await page.locator('#zodiac-title').textContent(), /双鱼/);
    await page.locator('#tab-sub-almanac').click();
    assert.match(await page.locator('#czodiac-title').textContent(), /猪/);
    checks.push('手动选择重启恢复');
    await page.locator('#btn-profile').click();
    await page.locator('#profile-birthday').fill('2024-02-09');
    await page.locator('#profile-form button[type=submit]').click();
    assert.match(await page.locator('#zodiac-title').textContent(), /水瓶/);
    assert.match(await page.locator('#czodiac-title').textContent(), /兔/);
    checks.push('生日跨农历新年生肖匹配');
    const beforeNativeShake = await page.evaluate(() => localStorage.getItem('xingyun.state.v1'));
    await page.evaluate(() => window.handleNativeShake());
    assert.equal(await page.evaluate(() => localStorage.getItem('xingyun.state.v1')), beforeNativeShake);
    await page.locator('[data-mod=divine]').click();
    await page.locator('#btn-trigger-shake').click();
    await page.locator('#divine-result-card').waitFor({ state: 'visible' });
    const oracle = await page.locator('#oracle-title').textContent();
    await page.locator('#btn-trigger-shake').click();
    assert.equal(await page.locator('#oracle-title').textContent(), oracle);
    await page.reload();
    await page.locator('[data-mod=divine]').click();
    assert.equal(await page.locator('#oracle-title').textContent(), oracle);
    await page.locator('[data-poster=oracle]').click();
    assert.equal(await page.locator('#poster-modal-preview').isVisible(), true);
    await page.locator('#btn-close-poster').click();
    checks.push('求签每日一次/重启恢复/独立海报/非灵签摇晃屏蔽');
    await page.locator('[data-mod=tarot]').click();
    await page.locator('.tarot-card-item').nth(6).click();
    await page.locator('#tarot-meaning-card').waitFor({ state: 'visible' });
    const tarot = await page.locator('#tarot-title').textContent();
    assert.ok(tarot.length > 3);
    await page.locator('#btn-draw-tarot').click();
    assert.equal(await page.locator('#tarot-title').textContent(), tarot);
    await page.locator('[data-poster=tarot]').click();
    await page.locator('#btn-close-poster').click();
    await page.reload();
    await page.locator('[data-mod=tarot]').click();
    assert.equal(await page.locator('#tarot-title').textContent(), tarot);
    checks.push('78牌抽取/牌义/每日锁定/重启恢复/塔罗海报');
    const selectionContext = await browser.newContext();
    const selectionPage = await selectionContext.newPage();
    await selectionPage.addInitScript(() => {
      let index = 77;
      crypto.getRandomValues = values => {
        const target = index === 31 ? 0 : index;
        values[0] = Math.floor((target + 0.5) / (index + 1) * 4294967296);
        index = Math.max(0, index - 1);
        return values;
      };
    });
    await selectionPage.goto(url);
    await selectionPage.locator('[data-mod=tarot]').click();
    await selectionPage.locator('.tarot-card-item').first().click();
    const selectedCard = await selectionPage.evaluate(() => Object.values(JSON.parse(localStorage.getItem('xingyun.state.v1')).daily)[0].tarot.id);
    assert.equal(selectedCard, 31);
    await selectionContext.close();
    checks.push('直觉选牌索引正确，无浮点误差换牌');
    await page.locator('[data-mod=lantern]').click();
    await page.locator('.wish-theme-pill').nth(1).click();
    await page.locator('#input-wish-text').fill('愿'.repeat(51));
    assert.equal(await page.locator('#btn-submit-wish').isDisabled(), true);
    await page.locator('#input-wish-text').fill('<img src=x onerror=alert(1)>愿平安');
    await page.locator('#btn-submit-wish').click();
    assert.match(await page.locator('#wish-history').textContent(), /逢考必过/);
    await page.reload();
    await page.locator('[data-mod=lantern]').click();
    assert.match(await page.locator('#wish-history').textContent(), /<img src=x/);
    assert.equal(await page.locator('#wish-history img').count(), 0);
    assert.equal(await page.locator('#wish-count').textContent(), '1盏明灯');
    checks.push('心愿主题/字数限制/持久化/输入文本安全');
    const yesterdayScores = await page.locator('#zodiac-metrics').textContent();
    await page.clock.setSystemTime(new Date('2026-10-14T00:00:01+08:00'));
    await page.evaluate(() => window.onNativeResume());
    assert.notEqual(await page.locator('#zodiac-metrics').textContent(), yesterdayScores);
    await page.locator('[data-mod=divine]').click();
    assert.equal(await page.locator('#divine-result-card').isVisible(), false);
    await page.locator('[data-mod=tarot]').click();
    assert.equal(await page.locator('#revealed-tarot-box').isVisible(), false);
    checks.push('跨零点日运刷新与抽取重置');
    await page.locator('[data-mod=fortune]').click();
    const client = await context.newCDPSession(page);
    await page.locator('#zodiac-ribbon').evaluate(node => { node.scrollLeft = 0; });
    const ribbon = await page.locator('#zodiac-ribbon').boundingBox();
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 340, y: ribbon.y + 20 }] });
    for (let step = 1; step <= 10; step++) await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 340 - step * 25, y: ribbon.y + 20 }] });
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    assert.ok(await page.locator('#zodiac-ribbon').evaluate(node => node.scrollLeft > 0));
    checks.push('横向真实触控事件滑动');
    await page.setViewportSize({ width: 360, height: 640 });
    await page.locator('#tab-sub-almanac').click();
    await page.locator('#app-screen-scroll-body').evaluate(node => { node.scrollTop = 0; });
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 180, y: 480 }] });
    for (let step = 1; step <= 12; step++) {
      await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 180, y: 480 - step * 20 }] });
      await page.waitForTimeout(20);
    }
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    assert.ok(await page.locator('#app-screen-scroll-body').evaluate(node => node.scrollTop > 0));
    await page.locator('#tab-sub-zodiac').click();
    checks.push('长黄历页面纵向触控滚动');
    for (const viewport of [{ width: 320, height: 568 }, { width: 360, height: 640 }, { width: 390, height: 844 }, { width: 412, height: 915 }, { width: 360, height: 340 }]) {
      await page.setViewportSize(viewport);
      await page.evaluate(() => window.setSystemInsets(28, 48));
      await page.locator('#btn-export-poster').scrollIntoViewIfNeeded();
      const button = await page.locator('#btn-export-poster').boundingBox();
      const dock = await page.locator('.floating-bottom-dock').boundingBox();
      assert.ok(button.y + button.height <= dock.y + 1);
      await page.locator('#btn-export-poster').click();
      const modal = await page.locator('#poster-modal-preview .poster-content-card').boundingBox();
      assert.ok(modal.y >= 28 && modal.y + modal.height <= viewport.height - 48 + 1);
      await page.locator('#btn-close-poster').scrollIntoViewIfNeeded();
      const close = await page.locator('#btn-close-poster').boundingBox();
      assert.ok(close.y >= 28 && close.y + close.height <= viewport.height - 48 + 1);
      if (viewport.width === 360 && viewport.height === 640) await page.screenshot({ path: path.join(output, 'poster-fixed.png') });
      await page.locator('#btn-close-poster').click();
    }
    checks.push('5种视口首页/弹窗安全区与键盘缩小视口');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#app-screen-scroll-body').evaluate(node => { node.scrollTop = 0; });
    await page.screenshot({ path: path.join(output, 'home-fixed.png') });
    assert.deepEqual(errors, []);
    assert.deepEqual(requests, []);
    checks.push('运行时无异常/无外部网络请求');
    const failureContext = await browser.newContext();
    const failurePage = await failureContext.newPage();
    await failurePage.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error('quota'); }; });
    await failurePage.goto(url);
    await failurePage.locator('[data-mod=divine]').click();
    await failurePage.locator('#btn-trigger-shake').click();
    assert.equal(await failurePage.locator('#divine-result-card').isVisible(), false);
    assert.match(await failurePage.locator('#app-toast').textContent(), /保存失败/);
    checks.push('存储失败不假报抽取成功');
    const corrupted = await browser.newContext();
    const corruptedPage = await corrupted.newPage();
    await corruptedPage.addInitScript(() => localStorage.setItem('xingyun.state.v1', '{broken'));
    await corruptedPage.goto(url);
    assert.equal(await corruptedPage.locator('#app-error').isVisible(), true);
    await corruptedPage.locator('#btn-sound').click();
    assert.equal(await corruptedPage.evaluate(() => localStorage.getItem('xingyun.state.v1')), '{broken');
    checks.push('损坏记录保护，不以空数据覆盖');
    await context.setOffline(true);
    await page.reload();
    assert.equal(await page.locator('#app-error').isVisible(), false);
    await page.locator('#btn-sound').click();
    await page.reload();
    assert.equal(await page.locator('#btn-sound').getAttribute('aria-pressed'), 'false');
    await page.locator('[data-mod=lantern]').click();
    assert.equal(await page.locator('#wish-count').textContent(), '1盏明灯');
    checks.push('离线重载与音效配置保存');
    const previewPage = await context.newPage();
    previewPage.on('pageerror', error => errors.push(error.message));
    await previewPage.goto(pathToFileURL(path.resolve(__dirname, '../preview.html')).href);
    const frame = previewPage.frameLocator('#app-preview');
    const appFrame = await (await previewPage.locator('#app-preview').elementHandle()).contentFrame();
    await frame.locator('#zodiac-title').waitFor({ state: 'visible' });
    for (const theme of ['gold','silver','rose','jade']) {
      await previewPage.locator('[data-theme=' + theme + ']').click();
      assert.equal(await previewPage.locator('[data-theme=' + theme + ']').getAttribute('aria-pressed'), 'true');
      const expectedColor = { gold: '#c5a059', silver: '#bcc8da', rose: '#e1b0b8', jade: '#a1c6b3' }[theme];
      await appFrame.waitForFunction(color => document.documentElement.style.getPropertyValue('--theme-primary') === color, expectedColor);
      assert.equal(await frame.locator('html').evaluate(node => node.style.getPropertyValue('--theme-primary')), expectedColor);
    }
    await frame.locator('[data-mod=tarot]').click();
    assert.equal(await frame.locator('#btn-draw-tarot').isVisible(), true);
    assert.deepEqual(errors, []);
    checks.push('四主题演示复用正式应用且交互可用');
    fs.writeFileSync(path.join(output, 'ui-results.json'), JSON.stringify({ checks, errors, requests }, null, 2));
    console.log(checks.map(check => 'PASS ' + check).join('\n'));
  } finally {
    for (const context of browser.contexts()) await context.close();
    await browser.close();
  }
}
run().catch(error => { console.error(error); process.exitCode = 1; });
